-- Tabla de confirmaciones de Huamanga Club. Pegar en Supabase → SQL Editor (proyecto nuevo).
create table if not exists public.rsvps (
  id          uuid primary key default gen_random_uuid(),
  created_at  timestamptz not null default now(),
  numero      integer generated by default as identity, -- N° de entrada (#001, #002…)
  nombre      text not null,
  email       text not null,
  cancion     text
);

-- Un email solo puede confirmar una vez (sin importar mayúsculas).
create unique index if not exists rsvps_email_unique on public.rsvps (lower(email));
create unique index if not exists rsvps_numero_unique on public.rsvps (numero);

-- Sin políticas: solo las funciones de Vercel (con la service role key) pueden leer/escribir.
alter table public.rsvps enable row level security;
